function likert(values: number[]): Record<string, number> {
  if (values.length !== LIKERT_QUESTIONS.length) throw new Error("Expected 30 likert values");
  return Object.fromEntries(LIKERT_QUESTIONS.map((q, i) => [q.id, values[i]]));
}

const W = (values: number[], emotional: number[], lifestyle: number[], communication: number[], goals: number[], intimacy: number[]) => [
  ...values,
  ...emotional,
  ...lifestyle,
  ...communication,
  ...goals,
  ...intimacy,
];

