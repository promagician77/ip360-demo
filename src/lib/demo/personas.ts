/** Generates in-memory profiles for every persona (no database required). */
export function buildDemoProfiles(): CompatibilityProfile[] {
  return DEMO_PERSONAS.map((p) =>
    generateProfile(p.responses, {
      profileId: `demo_${p.slug}`,
      lat: p.lat,
      lng: p.lng,
      generatedAt: new Date("2026-09-01T00:00:00Z"),
    }),
  );
}

export function personaBySlug(slug: string): DemoPersona | undefined {
  return DEMO_PERSONAS.find((p) => p.slug === slug);
}
